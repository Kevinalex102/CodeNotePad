    private void initializeFonts(){
        loadAvailableFonts();
        comboBox_font.addItemListener((ItemEvent ie) -> {
            if (ie.getStateChange() == ItemEvent.SELECTED){
                changeFontFamily();
            }
        });
        comboBox_font.setSelectedItem("Arial");
        spinner_fontSize.addChangeListener((ChangeEvent ce) -> {
            changeFontSize((int) spinner_fontSize.getValue());
        });
        changeFontFamily();
    }
    
    private void changeFontFamily(){
        Font oldFont = mainTextArea.getFont();
        Font newFont = new Font(
                comboBox_font.getSelectedItem().toString(),
                oldFont.getStyle(),
                oldFont.getSize()
        );
        mainTextArea.setFont(newFont);
    }
    
    private void changeFontFamily(String fontFamily){
        Font oldFont = mainTextArea.getFont();
        Font newFont = new Font(
                fontFamily,
                oldFont.getStyle(),
                oldFont.getSize()
        );
        mainTextArea.setFont(newFont);
    }

