    public File chooseFolder(){
        JFileChooser chooser;
        chooser = new JFileChooser(); 
        chooser.setCurrentDirectory(new java.io.File("user.home"));
        chooser.setFileSelectionMode(JFileChooser.DIRECTORIES_ONLY);
        chooser.setAcceptAllFileFilterUsed(false);
        if (chooser.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
            File folder = chooser.getSelectedFile();
            if(folder != null){
                return folder;
            }
        }
        else {
          System.out.println("No Selection ");
        }
        return null;
    }
    
    public File createFolder(){
        File selectedDirectory = chooseFolder();
        if(selectedDirectory == null){
            return null;
        }
        String DirectoryName = JOptionPane.showInputDialog(
            null, 
            "Digite o nome da nova pasta:", 
            "Nome da Pasta", 
            JOptionPane.QUESTION_MESSAGE
        );
        if (DirectoryName != null && !DirectoryName.trim().isEmpty()){
            File newFolder = new File(selectedDirectory, DirectoryName.trim());
            return newFolder;
        } 
        return null;
    }
    
    public File chooseImage(){
        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setCurrentDirectory(new File(System.getProperty("user.home")));
        
        int result = fileChooser.showOpenDialog(this);
        
        if (result == JFileChooser.APPROVE_OPTION) {
            File selectedFile = fileChooser.getSelectedFile();
            if(ImageFile.isImage(selectedFile)){
                return selectedFile;
            }
        }
        return null;
    }
    
    public void loadTextArea(String text, Color bgColor, Color fgColor, boolean bold, boolean italic, String fontFamily){
        editorPane.removeAll();
        mainTextArea.setText(text);
        mainTextArea.setBackground(bgColor);
        btn_bgColor.setBackground(bgColor);
        mainTextArea.setForeground(fgColor);
        btn_textColor.setBackground(fgColor);
        if(bold)changeFontStyle(Font.BOLD);
        if(italic)changeFontStyle(Font.ITALIC);
        changeFontFamily(fontFamily);
    }
    
    private void loadAvailableFonts(){
        GraphicsEnvironment ge = GraphicsEnvironment.getLocalGraphicsEnvironment();
        String[] defaultFonts = {"Arial", "Calibri", "Comic Sans MS", "Times New Roman"};
        HashSet<String> fontsSet = new HashSet<>(Arrays.asList(ge.getAvailableFontFamilyNames()));
        
        for(String font : defaultFonts){
            if(fontsSet.contains(font)){
                fontsSet.remove(font);
                comboBox_font.addItem(font);
            }
        }
        java.util.List<String> sortedFonts = new ArrayList<>(fontsSet);
        Collections.sort(sortedFonts);
        
        for (String font : sortedFonts){
            comboBox_font.addItem(font);
        }
    }

